let currentLang = "id";

function t(key) {
  const keys = key.split(".");
  let val = UI[currentLang];
  for (const k of keys) {
    val = val?.[k];
  }
  return val ?? key;
}

function loc(obj) {
  if (!obj) return "";
  if (typeof obj === "string") return obj;
  return obj[currentLang] ?? obj.id ?? "";
}

function locList(obj) {
  if (Array.isArray(obj)) return obj;
  return obj?.[currentLang] ?? obj?.id ?? [];
}

function esc(str) {
  const div = document.createElement("div");
  div.textContent = str;
  return div.innerHTML;
}

let sectionCounter = 0;

function sectionHeader(titleId, titleKey, subtitle = "") {
  sectionCounter += 1;
  const num = String(sectionCounter).padStart(2, "0");
  return `
    <div class="container section-header reveal">
      <span class="section-tag" aria-hidden="true">${num}</span>
      <h2 id="${titleId}">${esc(t(titleKey))}</h2>
      <div class="section-divider" aria-hidden="true"></div>
      ${subtitle ? `<p class="section-desc">${esc(subtitle)}</p>` : ""}
    </div>`;
}

