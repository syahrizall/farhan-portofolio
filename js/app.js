function buildNavLinksHtml() {
  const nav = UI[currentLang].nav;
  return NAV_ITEMS.map((key) => {
    const href = NAV_SECTION_MAP[key] || key;
    const label = nav[key] || key;
    return `<li><a href="#${href}" class="nav-link" data-nav="${esc(key)}">${esc(label)}</a></li>`;
  }).join("");
}

function renderNav() {
  const html = buildNavLinksHtml();
  const desktopMenu = document.getElementById("nav-menu");
  const mobileMenu = document.getElementById("nav-menu-mobile");
  if (desktopMenu) desktopMenu.innerHTML = html;
  if (mobileMenu) mobileMenu.innerHTML = html;
  updateHeaderChrome();
}

